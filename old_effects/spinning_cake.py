# ---------------------------------------------------------------------------
# Audio state
# ---------------------------------------------------------------------------
_synth      = None
_note_idx   = 0
_state      = 0   # 0 = note playing, 1 = gap before next note
_note_end   = 0
_next_start = 0
_volume     = 0.1


def _start_note():
    global _note_idx, _note_end, _next_start, _state
    freq, play_ms, gap_ms = _MELODY[_note_idx]
    _note_idx = (_note_idx + 1) % len(_MELODY)
    _synth.frequency(round(freq))
    _synth.trigger_attack()
    now = time.ticks_ms()
    # Preserve total note+gap duration: borrow from play_ms when gap is too short
    if gap_ms < _MIN_GAP:
        actual_play = max(play_ms - (_MIN_GAP - gap_ms), 1)
        actual_gap  = _MIN_GAP
    else:
        actual_play = play_ms
        actual_gap  = gap_ms
    _note_end   = time.ticks_add(now, int(actual_play / _SPEED))
    _next_start = time.ticks_add(_note_end, int(actual_gap  / _SPEED))
    _state = 0


def _read_volume():
    global _volume
    if cu.is_pressed(CosmicUnicorn.SWITCH_VOLUME_UP):
        _volume = min(_volume + 0.01, 1.0)
        cu.set_volume(_volume)
    if cu.is_pressed(CosmicUnicorn.SWITCH_VOLUME_DOWN):
        _volume = max(_volume - 0.01, 0.0)
        cu.set_volume(_volume)


def init():
    global _phase, _synth, _note_idx, _state
    _phase    = 0.0
    _note_idx = 0
    _state    = 0

    if cu is not None:
        _synth = cu.synth_channel(0)
        _synth.configure(
            waveforms=Channel.SQUARE,
            attack=0.002,
            decay=0.0,
            sustain=1.0,
            release=0.010,
            volume=_volume,
        )
        cu.set_volume(_volume)
        cu.play_synth()
        _start_note()


def draw():
    global _phase, _state
    gfx = graphics

    if cu is not None:
        _read_volume()

    if _synth is not None:
        now = time.ticks_ms()
        if _state == 0 and time.ticks_diff(now, _note_end) >= 0:
            _synth.trigger_release()
            _state = 1
        elif _state == 1 and time.ticks_diff(now, _next_start) >= 0:
            _start_note()

    p_off    = gfx.create_pen(*_OFF)
    p_orange = gfx.create_pen(*_ORANGE)
    p_white  = gfx.create_pen(*_WHITE)
    A2       = _A * _A

    for x in range(_W):
        dx       = x - _CX
        dx2_norm = dx * dx / A2

        if dx2_norm > 1.0:
            gfx.set_pen(p_off)
            for y in range(_W):
                gfx.pixel(x, y)
        else:
            factor   = math.sqrt(1.0 - dx2_norm)
            top_top  = _TOP_CY - _B * factor
            top_bot  = _TOP_CY + _B * factor
            body_bot = _BOT_CY + _B * factor
            body_mid = (_TOP_CY + _BOT_CY) * 0.5 + _B * factor
            theta    = math.acos(dx / _A)
            y_wave   = body_mid - _AMPLITUDE * _HALF_H * math.sin(_FREQUENCY * theta + _phase)

            for y in range(_W):
                if y < top_top or y > body_bot:
                    gfx.set_pen(p_off)
                elif y <= top_bot:
                    gfx.set_pen(p_orange)
                else:
                    gfx.set_pen(p_orange if y < y_wave else p_white)
                gfx.pixel(x, y)

    # --- disc specks: fixed points orbiting the centre like dust on a record ---
    rot = _phase / _CANDLE_PHASE_DIV
    for r, phi_world, bright in _SPECKS:
        phi_v = phi_world - rot
        sx = int(round(_CX + r * math.cos(phi_v)))
        sy = int(round(_TOP_CY + (_B / _A) * r * math.sin(phi_v)))
        if 0 <= sx < _W and 0 <= sy < _W:
            gfx.set_pen(gfx.create_pen(min(255, int(255 * bright)), min(255, int(140 * bright)), 0))
            gfx.pixel(sx, sy)

    # --- age candles ---
    cos_t     = math.cos(_phase / _CANDLE_PHASE_DIV)
    sin_t     = math.sin(_phase / _CANDLE_PHASE_DIV)
    half_w    = (_CANDLE_W - 1) * 0.5
    b_over_a  = _B / _A
    p_wax     = gfx.create_pen(*_WAXCOLOR)
    p_flame0  = gfx.create_pen(255, 255,   0)
    p_flame1  = gfx.create_pen(255, 160,   0)
    flicker   = int(_phase * 11) & 1

    for u in range(_CANDLE_W):
        h  = u - half_w
        sx = int(round(_CX + h * cos_t))
        if sx < 0 or sx >= _W:
            continue

        # oblique y-shift: each column rises or falls as it rotates into/out of depth
        base = _CANDLE_BASE_Y + int(round(-b_over_a * h * sin_t))

        for row in range(_CANDLE_H):
            if _CANDLE_BMP[row][u]:
                sy = base - (_CANDLE_H - 1 - row)
                if 0 <= sy < _W:
                    gfx.set_pen(p_wax)
                    gfx.pixel(sx, sy)

        # flame only above wick pixels (row 0 of bitmap)
        if _CANDLE_BMP[0][u]:
            fy = base - _CANDLE_H  # one above top row
            fp = p_flame0 if (flicker + u) & 1 else p_flame1
            if 0 <= fy < _W:
                gfx.set_pen(fp)
                gfx.pixel(sx, fy)
            if 0 <= fy - 1 < _W:
                gfx.set_pen(p_flame1)
                gfx.pixel(sx, fy - 1)

    _phase += _PHASE_SPEED


def deinit():
    if _synth is not None:
        _synth.trigger_release()
        cu.stop_playing()
