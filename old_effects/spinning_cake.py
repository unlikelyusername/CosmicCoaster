def _build_age_bitmap(age):
    d0, d1 = _DIGIT_SRC[age // 10], _DIGIT_SRC[age % 10]
    rows = []
    for r in range(8):
        row = [1 if c == '#' else 0 for c in d0[r]]
        row.append(0)
        row += [1 if c == '#' else 0 for c in d1[r]]
        rows.append(row)
    return rows



